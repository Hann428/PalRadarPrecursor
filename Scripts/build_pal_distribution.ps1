param(
    [string]$FModelRoot = "D:\PalOutput\Exports\Pal\Content\Pal",
    [string]$OutputLua = ".\generated_pal_distribution.lua",
    [string]$OutputCsv = ".\generated_pal_distribution_summary.csv"
)

$ErrorActionPreference = "Stop"

function Read-DataTableRows {
    param([string]$Path)
    if (-not (Test-Path -LiteralPath $Path)) { return @() }
    $json = Get-Content -LiteralPath $Path -Raw -Encoding UTF8 | ConvertFrom-Json
    $rows = @()
    foreach ($asset in @($json)) {
        if ($asset.Rows) {
            foreach ($prop in $asset.Rows.PSObject.Properties) {
                $rows += [pscustomobject]@{
                    Name = [string]$prop.Name
                    Value = $prop.Value
                }
            }
        }
    }
    return $rows
}

function Clean-Value {
    param([object]$Value)
    if ($null -eq $Value) { return "" }
    $s = [string]$Value
    if ($s -eq "None") { return "" }
    return $s.Trim()
}

function Normalize-PalId {
    param([string]$PalId)
    $id = Clean-Value $PalId
    if (-not $id) { return "" }
    $id = $id -replace "^BOSS_", ""
    $id = $id -replace "^GYM_", ""
    $id = $id -replace "^RAID_", ""
    $id = $id -replace "^Quest_[^_]+_", ""
    $id = $id -replace "_Tower$", ""
    $id = $id -replace "_Oilrig$", ""
    $id = $id -replace "_Raid$", ""
    return $id
}

function Lua-String {
    param([object]$Value)
    if ($null -eq $Value) { return '""' }
    $s = [string]$Value
    $s = $s -replace "\\", "\\"
    $s = $s -replace '"', '\"'
    $s = $s -replace "`r", "\r"
    $s = $s -replace "`n", "\n"
    return '"' + $s + '"'
}

function Get-CatalogIdSet {
    param([string]$Path)
    $ids = @{}
    foreach ($row in @(Read-DataTableRows $Path)) {
        $rawId = [string]$row.Name
        $value = $row.Value
        if (-not $value -or $value.IsPal -ne $true) { continue }
        $dexNo = [int]($value.ZukanIndex)
        if ($dexNo -le 0) { continue }
        if ($rawId -match "^(BOSS_|GYM_|RAID_|Quest_)") { continue }
        if ($rawId -match "(_Oilrig|_Raid)$") { continue }
        $palId = Normalize-PalId $rawId
        if (-not $palId -or $palId -match "^SUMMON_") { continue }
        $ids[$palId] = $true
    }
    return $ids
}

function Add-Location {
    param(
        [System.Collections.Generic.List[object]]$Points,
        [hashtable]$Seen,
        [object]$Location
    )
    if (-not $Location) { return }
    $x = [double]$Location.X
    $y = [double]$Location.Y
    $z = [double]$Location.Z
    $key = "{0},{1},{2}" -f ([math]::Round($x, 0)), ([math]::Round($y, 0)), ([math]::Round($z, 0))
    if ($Seen.ContainsKey($key)) { return }
    $Seen[$key] = $true
    $Points.Add([pscustomobject]@{
        X = [math]::Round($x, 1)
        Y = [math]::Round($y, 1)
        Z = [math]::Round($z, 1)
    })
}

$catalogIds = Get-CatalogIdSet (Join-Path $FModelRoot "DataTable\Character\DT_PalMonsterParameter.json")
$distributionRows = Read-DataTableRows (Join-Path $FModelRoot "DataTable\UI\DT_PaldexDistributionData.json")

$entries = @()
foreach ($row in @($distributionRows)) {
    $rawId = [string]$row.Name
    if ($rawId -match "^(BOSS_|GYM_|RAID_|Quest_)") { continue }
    if ($rawId -match "(_Oilrig|_Raid)$") { continue }

    $palId = Normalize-PalId $rawId
    if (-not $palId -or -not $catalogIds.ContainsKey($palId)) { continue }

    $data = $row.Value
    $points = New-Object System.Collections.Generic.List[object]
    $seen = @{}
    $dayCount = 0
    $nightCount = 0

    if ($data.dayTimeLocations -and $data.dayTimeLocations.Locations) {
        foreach ($loc in @($data.dayTimeLocations.Locations)) {
            $dayCount++
            Add-Location $points $seen $loc
        }
    }
    if ($data.nightTimeLocations -and $data.nightTimeLocations.Locations) {
        foreach ($loc in @($data.nightTimeLocations.Locations)) {
            $nightCount++
            Add-Location $points $seen $loc
        }
    }

    if ($points.Count -le 0) { continue }
    $encoded = ($points | ForEach-Object { "{0},{1},{2}" -f $_.X, $_.Y, $_.Z }) -join ";"
    $entries += [pscustomobject]@{
        Id = $palId
        DayCount = $dayCount
        NightCount = $nightCount
        PointCount = $points.Count
        EncodedPoints = $encoded
    }
}

$entries = @($entries | Sort-Object Id)
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("-- generated_pal_distribution.lua")
$lines.Add("-- Generated by build_pal_distribution.ps1. Do not edit by hand.")
$lines.Add("return {")
$lines.Add("    PalDistributions = {")
foreach ($entry in $entries) {
    $lines.Add("        [$(Lua-String $entry.Id)] = {")
    $lines.Add("            PointCount = $($entry.PointCount),")
    $lines.Add("            DayCount = $($entry.DayCount),")
    $lines.Add("            NightCount = $($entry.NightCount),")
    $lines.Add("            EncodedPoints = $(Lua-String $entry.EncodedPoints),")
    $lines.Add("        },")
}
$lines.Add("    },")
$lines.Add("    Metadata = { PalDistributionRows = $(@($entries).Count), PalDistributionPoints = $(($entries | Measure-Object -Property PointCount -Sum).Sum) },")
$lines.Add("}")

$outDir = Resolve-Path -LiteralPath (Split-Path -Parent $OutputLua)
[IO.File]::WriteAllLines((Join-Path $outDir (Split-Path -Leaf $OutputLua)), $lines, [Text.UTF8Encoding]::new($false))

$entries |
    Select-Object Id,PointCount,DayCount,NightCount |
    Export-Csv -LiteralPath $OutputCsv -NoTypeInformation -Encoding UTF8

Write-Host "Generated $OutputLua"
Write-Host "Generated $OutputCsv"
Write-Host ("PalDistributionRows: {0}" -f @($entries).Count)
Write-Host ("PalDistributionPoints: {0}" -f (($entries | Measure-Object -Property PointCount -Sum).Sum))
