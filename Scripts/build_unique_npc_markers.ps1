param(
    [string]$InputCsv = ".\npc_spawner_candidates_summary.csv",
    [string]$OutputLua = ".\generated_unique_npc_markers.lua",
    [string]$OutputCsv = ".\generated_unique_npc_markers_summary.csv"
)

$ErrorActionPreference = "Stop"

function Lua-String {
    param([object]$Value)
    if ($null -eq $Value) { return '""' }
    $s = [string]$Value
    $s = $s -replace "\\", "\\"
    $s = $s -replace '"', '\"'
    $s = $s -replace "`r", "\r"
    $s = $s -replace "`n", "\n"
    return '"' + $s + '"'
}

function Clean-Value {
    param([object]$Value)
    if ($null -eq $Value) { return "" }
    $s = [string]$Value
    if ($s -eq "None") { return "" }
    return $s.Trim()
}

function Is-MerchantCandidate {
    param([object]$Row)

    $text = @(
        (Clean-Value $Row.Type),
        (Clean-Value $Row.ActorLabel),
        (Clean-Value $Row.UniqueName),
        (Clean-Value $Row.OtomoName)
    ) -join " "

    return ($text -match "PalShop|Shop|MedalTrader|BountyTrader|ArenaShop|DarkTrader|MerchantwithPAL|SalesPerson|PalDealer|Dealer")
}

function Is-BossSpawner {
    param([object]$Row)
    return ((Clean-Value $Row.Type) -match "BossBase|HumanNPCBoss")
}

function New-Marker {
    param(
        [object]$Row,
        [string]$Category,
        [int]$Index
    )

    $uniqueName = Clean-Value $Row.UniqueName
    $actorLabel = Clean-Value $Row.ActorLabel
    $type = Clean-Value $Row.Type
    $name = $uniqueName
    if (-not $name) { $name = $actorLabel }
    if (-not $name) { $name = Clean-Value $Row.Name }

    return [pscustomobject]@{
        Category = $Category
        Id = ("unique_npc_{0}_{1:000}" -f $Category.ToLowerInvariant(), $Index)
        Name = $name
        UniqueName = $uniqueName
        OtomoName = Clean-Value $Row.OtomoName
        ActorLabel = $actorLabel
        SpawnerType = $type
        Level = Clean-Value $Row.Level
        X = [double]$Row.X
        Y = [double]$Row.Y
        Z = [double]$Row.Z
        Source = "FModel:PL_MainWorld5 WorldPartition NPC spawners"
    }
}

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$inputPath = if ([IO.Path]::IsPathRooted($InputCsv)) { $InputCsv } else { Join-Path $scriptDir $InputCsv }
$outputLuaPath = if ([IO.Path]::IsPathRooted($OutputLua)) { $OutputLua } else { Join-Path $scriptDir $OutputLua }
$outputCsvPath = if ([IO.Path]::IsPathRooted($OutputCsv)) { $OutputCsv } else { Join-Path $scriptDir $OutputCsv }

if (-not (Test-Path -LiteralPath $inputPath)) {
    throw "Missing input CSV: $inputPath"
}

$rows = Import-Csv -LiteralPath $inputPath
$markers = New-Object System.Collections.Generic.List[object]
$merchantIndex = 0
$otherIndex = 0

foreach ($row in $rows) {
    if (-not $row.X -or -not $row.Y) { continue }

    $uniqueName = Clean-Value $row.UniqueName
    $actorLabel = Clean-Value $row.ActorLabel
    $isMerchant = Is-MerchantCandidate $row
    $isBoss = Is-BossSpawner $row

    if ($isMerchant -and -not ($isBoss -and $uniqueName -notmatch "DarkTrader|BountyTrader|ArenaShop")) {
        $merchantIndex++
        $markers.Add((New-Marker $row "NPCMerchant" $merchantIndex))
        continue
    }

    if (-not $uniqueName) { continue }
    if ($isBoss) { continue }
    if ($uniqueName -match "^Police_WarningOilrig$") { continue }
    if ($isMerchant) { continue }

    $otherIndex++
    $markers.Add((New-Marker $row "NPCOther" $otherIndex))
}

# One DarkTrader actor is embedded directly in PL_MainWorld5 rather than in a generated cell.
$merchantIndex++
$markers.Add([pscustomobject]@{
    Category = "NPCMerchant"
    Id = ("unique_npc_npcmerchant_{0:000}" -f $merchantIndex)
    Name = "DarkTrader"
    UniqueName = "DarkTrader"
    OtomoName = "Werewolf"
    ActorLabel = "BP_MonoNPCSpawner"
    SpawnerType = "BP_MonoNPCSpawner_C"
    Level = ""
    X = -209317.05
    Y = 23344.367
    Z = -1935.6077
    Source = "FModel:PL_MainWorld5 direct actor"
})

$markers = @($markers | Sort-Object Category, Name, X, Y)
$merchantRows = @($markers | Where-Object { $_.Category -eq "NPCMerchant" }).Count
$otherRows = @($markers | Where-Object { $_.Category -eq "NPCOther" }).Count

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("-- generated_unique_npc_markers.lua")
$lines.Add("-- Generated by build_unique_npc_markers.ps1. Do not edit by hand.")
$lines.Add("return {")
foreach ($category in @("NPCMerchant", "NPCOther")) {
    $lines.Add("    $category = {")
    foreach ($entry in @($markers | Where-Object { $_.Category -eq $category })) {
        $lines.Add("        {")
        $lines.Add("            Id = $(Lua-String $entry.Id),")
        $lines.Add("            Name = $(Lua-String $entry.Name),")
        $lines.Add("            X = $($entry.X),")
        $lines.Add("            Y = $($entry.Y),")
        $lines.Add("            Z = $($entry.Z),")
        $lines.Add("            IconIndex = 11,")
        $lines.Add("            Source = $(Lua-String $entry.Source),")
        $lines.Add("            UniqueName = $(Lua-String $entry.UniqueName),")
        $lines.Add("            OtomoName = $(Lua-String $entry.OtomoName),")
        $lines.Add("            ActorLabel = $(Lua-String $entry.ActorLabel),")
        $lines.Add("            SpawnerType = $(Lua-String $entry.SpawnerType),")
        $lines.Add("            Level = $(Lua-String $entry.Level),")
        $lines.Add("        },")
        $lines.Add("")
    }
    $lines.Add("    },")
}
$lines.Add("    Metadata = {")
$lines.Add("        UniqueNpcMarkerRows = $($markers.Count),")
$lines.Add("        NPCMerchantRows = $merchantRows,")
$lines.Add("        NPCOtherRows = $otherRows,")
$lines.Add("    },")
$lines.Add("}")

[IO.File]::WriteAllLines($outputLuaPath, $lines, [Text.UTF8Encoding]::new($false))
$markers | Export-Csv -LiteralPath $outputCsvPath -NoTypeInformation -Encoding UTF8

Write-Host "Generated $outputLuaPath"
Write-Host "Generated $outputCsvPath"
Write-Host ("UniqueNpcMarkerRows: {0} merchant={1} other={2}" -f $markers.Count, $merchantRows, $otherRows)
