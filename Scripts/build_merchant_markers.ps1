param(
    [string]$FModelRoot = "D:\PalOutput\Exports\Pal\Content\Pal",
    [string]$OutputLua = ".\generated_merchant_markers.lua",
    [string]$OutputCsv = ".\generated_merchant_markers_summary.csv"
)

$ErrorActionPreference = "Stop"

function Lua-String {
    param([object]$Value)
    if ($null -eq $Value) { return '""' }
    $s = [string]$Value
    $s = $s -replace "\\", "\\"
    $s = $s -replace '"', '\"'
    $s = $s -replace "`r", "\r"
    $s = $s -replace "`n", "\n"
    return '"' + $s + '"'
}

function Clean-Value {
    param([object]$Value)
    if ($null -eq $Value) { return "" }
    $s = [string]$Value
    if ($s -eq "None") { return "" }
    return $s.Trim()
}

$path = Join-Path $FModelRoot "DataTable\Spawner\DT_PalSpawnerPlacement.json"
if (-not (Test-Path -LiteralPath $path)) {
    throw "Missing DT_PalSpawnerPlacement.json: $path"
}

$json = Get-Content -LiteralPath $path -Raw -Encoding UTF8 | ConvertFrom-Json
$patterns = "merchant|marchant|sales|salsman|trader|dealer|shop|darktrader|medaltrader|bountytrader|arenashop"
$entries = @()

foreach ($prop in @($json[0].Rows.PSObject.Properties)) {
    $row = $prop.Value
    if (-not $row -or -not $row.Location) { continue }

    $assetPath = ""
    if ($row.SpawnerClass -and $row.SpawnerClass.AssetPathName) {
        $assetPath = Clean-Value $row.SpawnerClass.AssetPathName
    }

    $parts = @(
        $prop.Name,
        (Clean-Value $row.InstanceName),
        (Clean-Value $row.SpawnerName),
        (Clean-Value $row.SpawnerType),
        (Clean-Value $row.PlacementType),
        $assetPath
    )
    $text = ($parts -join " ")
    if ($text -notmatch $patterns) { continue }

    $name = Clean-Value $row.InstanceName
    if (-not $name) { $name = Clean-Value $row.SpawnerName }
    if (-not $name) { $name = "MerchantSpawner_$($prop.Name)" }

    $entries += [pscustomobject]@{
        Id = "merchant_spawner_$($prop.Name)"
        Name = $name
        SpawnerName = Clean-Value $row.SpawnerName
        SpawnerType = Clean-Value $row.SpawnerType
        PlacementType = Clean-Value $row.PlacementType
        AssetPath = $assetPath
        X = [double]$row.Location.X
        Y = [double]$row.Location.Y
        Z = [double]$row.Location.Z
    }
}

$entries = @($entries | Sort-Object Id)

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("-- generated_merchant_markers.lua")
$lines.Add("-- Generated by build_merchant_markers.ps1. Do not edit by hand.")
$lines.Add("return {")
$lines.Add("    NPCMerchant = {")
foreach ($entry in $entries) {
    $lines.Add("        {")
    $lines.Add("            Id = $(Lua-String $entry.Id),")
    $lines.Add("            Name = $(Lua-String $entry.Name),")
    $lines.Add("            X = $($entry.X),")
    $lines.Add("            Y = $($entry.Y),")
    $lines.Add("            Z = $($entry.Z),")
    $lines.Add("            IconIndex = 11,")
    $lines.Add("            Source = $(Lua-String 'FModel:DT_PalSpawnerPlacement'),")
    $lines.Add("            SpawnerName = $(Lua-String $entry.SpawnerName),")
    $lines.Add("            SpawnerType = $(Lua-String $entry.SpawnerType),")
    $lines.Add("            PlacementType = $(Lua-String $entry.PlacementType),")
    $lines.Add("            AssetPath = $(Lua-String $entry.AssetPath),")
    $lines.Add("        },")
}
$lines.Add("    },")
$lines.Add("    Metadata = { MerchantMarkerRows = $(@($entries).Count) },")
$lines.Add("}")

$outDir = Resolve-Path -LiteralPath (Split-Path -Parent $OutputLua)
[IO.File]::WriteAllLines((Join-Path $outDir (Split-Path -Leaf $OutputLua)), $lines, [Text.UTF8Encoding]::new($false))

$entries | Export-Csv -LiteralPath $OutputCsv -NoTypeInformation -Encoding UTF8

Write-Host "Generated $OutputLua"
Write-Host "Generated $OutputCsv"
Write-Host ("MerchantMarkerRows: {0}" -f @($entries).Count)
